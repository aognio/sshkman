use sshkma_domain::{
    DeviceId, DomainError, FileAction, FileFingerprint, HostAlias, IdentityId, InstallationPlan,
    ManagedFile, ManagedFileType, OperationId, SessionId, Slug, UserId,
};

#[test]
fn test_slug_validation() {
    assert!(Slug::parse("prod-bastion_01").is_ok());
    assert!(Slug::parse("key1").is_ok());

    // Invalid cases
    assert_eq!(
        Slug::parse("").unwrap_err(),
        DomainError::InvalidSlug("slug cannot be empty".into())
    );
    assert!(Slug::parse("../evil").is_err());
    assert!(Slug::parse("has space").is_err());
    assert!(Slug::parse("has/slash").is_err());
    let long_slug = "a".repeat(65);
    assert!(Slug::parse(&long_slug).is_err());
}

#[test]
fn test_opaque_ids_and_correlation() {
    let user_id = UserId::new();
    let dev_id = DeviceId::new();
    let sess_id = SessionId::new();
    let ident_id = IdentityId::new();
    let op_id = OperationId::new();

    assert_eq!(user_id.as_str().len(), 36);
    assert_eq!(dev_id.as_str().len(), 36);
    assert_eq!(sess_id.as_str().len(), 36);
    assert_eq!(ident_id.as_str().len(), 36);
    assert_eq!(op_id.as_str().len(), 36);

    let parsed_user = UserId::parse(user_id.as_str()).expect("parse valid user id");
    assert_eq!(user_id, parsed_user);
}

#[test]
fn test_host_alias() {
    let alias = HostAlias::parse("prod-server").unwrap();
    assert_eq!(alias.as_str(), "prod-server");
    assert!(HostAlias::parse("").is_err());
    assert!(HostAlias::parse("invalid alias with spaces").is_err());
}

#[test]
fn test_managed_file_fingerprint_and_action() {
    let content = b"Host example\n    HostName 1.2.3.4\n";
    let file = ManagedFile::new(
        "~/.ssh/managed/example.conf",
        ManagedFileType::SshConfig,
        0o600,
        content.to_vec(),
    );

    let fp = FileFingerprint::compute(content);
    assert_eq!(file.fingerprint(), &fp);

    let mut plan = InstallationPlan::default();
    plan.add_action(FileAction::Create(file.clone()));
    assert_eq!(plan.actions().len(), 1);
    assert!(!plan.is_empty());
}

use proptest::prelude::*;

proptest! {
    #[test]
    fn prop_slug_roundtrip(s in "[a-zA-Z0-9_-]{1,64}") {
        let slug = Slug::parse(&s).expect("valid slug generated by regex");
        prop_assert_eq!(slug.as_str(), s);
    }

    #[test]
    fn prop_slug_rejects_slashes_and_dots(s in ".*[/\\.\\s]+.*") {
        if !s.is_empty() && s.len() <= 64 {
            let res = Slug::parse(&s);
            prop_assert!(res.is_err());
        }
    }
}

proptest! {
    #[test]
    fn prop_host_alias_roundtrip(s in "[a-zA-Z0-9_-]{1,64}") {
        let a = HostAlias::parse(&s).expect("valid alias");
        prop_assert_eq!(a.as_str(), s);
    }

    #[test]
    fn prop_user_id_parse_roundtrip(_n in 0u8..1u8) {
        let id = UserId::new();
        let parsed = UserId::parse(id.as_str()).unwrap();
        prop_assert_eq!(id, parsed);
    }
}
